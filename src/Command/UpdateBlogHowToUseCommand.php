    public function __construct(
        private BlogPostRepository $postRepository,
        private EntityManagerInterface $em,
    ) {
        parent::__construct();
    }

    protected function execute(InputInterface $input, OutputInterface $output): int
    {
        $io = new SymfonyStyle($input, $output);

        $articles = $this->getArticles();

        foreach ($articles as $data) {
            $post = $this->postRepository->findOneBy(['slug' => $data['slug']]);
            if (!$post) {
                $io->warning(sprintf('Post "%s" not found, skipping.', $data['slug']));
                continue;
            }

            $post->setTitleBg($data['title_bg']);
            $post->setExcerptBg($data['excerpt_bg']);
            $post->setContentBg($data['content_bg']);

            $io->text(sprintf('Updated: %s', $data['title_bg']));
        }

        $this->em->flush();
        $io->success('All articles updated.');

        return Command::SUCCESS;
    }

